# Braille dot positions: left/right columns, with the fourth row in bits 6/7.
DOT_BITS = ((0, 3), (1, 4), (2, 5), (6, 7))


def pixel_title(value: str, width: int) -> list[str]:
    if not value or len(value) * 3 > width or any(char not in GLYPHS for char in value):
        return []
    glyphs = [GLYPHS[char].split('/') for char in value]
    pixels = [''.join(glyph[row] + '0' for glyph in glyphs) for row in range(7)]
    pixels.append('0' * len(pixels[0]))
    lines = []
    for y in range(0, 8, 4):
        line = ''
        for x in range(0, len(pixels[0]), 2):
            mask = sum(1 << DOT_BITS[dy][dx] for dy in range(4) for dx in range(2)
                       if pixels[y + dy][x + dx] == '1')
            line += chr(0x2800 + mask) if mask else ' '
        lines.append(line.rstrip())
    return lines
